// Загальний "Гідрант справний?" — окремий пункт (Q1), не входить у секції.
export const OVERALL_KEY = 'isWorking';
export const OVERALL_LABEL = 'Пожежний гідрант перебуває у справному стані?';
export const OVERALL_DEFECT = 'ПГ несправний';

export const ALL_CHECK_KEYS = [
  OVERALL_KEY,
  ...CHECKLIST_SECTIONS.flatMap((s) => s.items.map((i) => i.key)),
];

// Список текстів виявлених недоліків для перевірки (failed-пункти + вільний коментар).
export function getInspectionDefects(insp) {
  if (!insp) return [];
  const defects = [];
  if (insp[OVERALL_KEY] === false) defects.push(OVERALL_DEFECT);
  for (const section of CHECKLIST_SECTIONS) {
    for (const item of section.items) {
      if (insp[item.key] === false) defects.push(item.defect);
    }
  }
  if (insp.weakness?.trim()) defects.push(insp.weakness.trim());
  return defects;
}
